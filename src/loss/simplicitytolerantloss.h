#pragma once

#include <string>

#include "torchph.h"


// Cross entropy against a label that accepts more than one class.
//
// A spectra generated by "r-rc-rc" whose last block contributes nothing is equally well described by
// "r-rc", and scoring it with NLL tells the network to look for a time constant that is not in the
// data.
class SimplicityTolerantLoss : public torch::nn::Module
{
	static constexpr double WEIGHT_FLOOR = 1e-30;

	torch::Tensor classWeights;

	public:
		SimplicityTolerantLoss(torch::Tensor classWeights = torch::Tensor());

		torch::Tensor forward(torch::Tensor logProbabilities, torch::Tensor labelWeights) const;

		inline torch::Tensor operator()(torch::Tensor logProbabilities, torch::Tensor labelWeights) const
		{
			return forward(logProbabilities, labelWeights);
		}
};
